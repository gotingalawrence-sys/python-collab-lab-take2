# Student D Anna - swap.py
# Practices: variables, tuple unpacking, the "temp variable" pattern

def swap_with_temp(a, b):
  temp = a
  a = b
  b = temp
  return a, b

def swap_pythonic (a, b):
  a, b = b, a
  return a, b

if __name__ == "__main__":
  x, y = 5, 10
  print("Before:", x, y)
  x, y = swap_with_temp(x, y)
  print("After temp swap:", x, y)
  x, y = swap_pythonic(x, y)
  print("After pythonic swap:", x, y)